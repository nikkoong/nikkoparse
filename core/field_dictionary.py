def find_by_label(label_text: str) -> Optional[Dict]:
    """
    Find a field entry by fuzzy label matching

    Args:
        label_text: Label text to search for (substring match, case-insensitive)

    Returns:
        First matching field entry or None
    """
    if not label_text:
        return None

    label_lower = label_text.lower().strip()

    # First try exact match
    for entry in FIELD_DICTIONARY:
        if entry["label"].lower() == label_lower:
            return entry

    # Then try substring match
    for entry in FIELD_DICTIONARY:
        entry_label_lower = entry["label"].lower()
        if label_lower in entry_label_lower or entry_label_lower in label_lower:
            return entry

    return None
